#!/usr/bin/env node
/**
 * Generate SQL that moves the single pawbook_state JSON blob into the
 * relational tables defined in 02-enhanced-schema.sql.
 *
 * Why this exists
 * ---------------
 * The whole app currently lives in one row: `pawbook_state`, key
 * `pawbook-animal-storage`, holding every animal, comment, memory and medical
 * record as one JSON document. Every browser rewrites the entire document on
 * every action. lib/state-merge.ts makes concurrent writes converge instead of
 * clobbering each other, but that is a stopgap — with real rows the problem
 * does not exist, and per-row RLS becomes possible.
 *
 * READ THIS BEFORE RUNNING
 * ------------------------
 * The tables in 02-enhanced-schema.sql gate every write on `auth.uid()`, and
 * PawBook has no authentication — contributions are anonymous, and the API
 * writes with the service-role key, which bypasses RLS entirely. So moving the
 * data is necessary but not sufficient: until the app can sign people in (even
 * Supabase anonymous sign-in, which needs no UI change), the new tables would
 * either reject every write or have to be written through the same service-role
 * bypass, which gains nothing over the blob.
 *
 * The order is therefore: sign-in first, then this migration, then repoint the
 * client. This script does the middle step and nothing else. It writes a .sql
 * file and never touches the database.
 *
 * Usage
 * -----
 *   node scripts/03-migrate-blob-to-tables.mjs <state.json> [out.sql]
 *
 * where <state.json> is the persisted blob — either the value of the `data`
 * column, or the readable export in the backups folder.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const [, , inputPath, outputPath = 'scripts/03-migrate-data.sql'] = process.argv;

if (!inputPath) {
  console.error('usage: node scripts/03-migrate-blob-to-tables.mjs <state.json> [out.sql]');
  process.exit(1);
}

/** Quote a value for SQL, or NULL. Dollar-quoted so no escaping is needed. */
function q(value) {
  if (value === null || value === undefined || value === '') return 'NULL';
  return `$m$${String(value)}$m$`;
}

function ts(value) {
  if (!value) return 'NULL';
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime()) ? 'NULL' : `$m$${parsed.toISOString()}$m$::timestamp`;
}

const raw = JSON.parse(readFileSync(inputPath, 'utf8'));
const animals = raw?.state?.animals ?? raw?.animals ?? [];
if (!Array.isArray(animals) || animals.length === 0) {
  console.error('No animals found in that file.');
  process.exit(1);
}

const out = [];
const counts = { animals: 0, comments: 0, memories: 0, medical: 0, care: 0 };

out.push('-- Generated by scripts/03-migrate-blob-to-tables.mjs. Review before running.');
out.push('-- Idempotent: re-running updates rather than duplicating.');
out.push('-- Legacy numeric ids are preserved in animals.notes so the blob and the');
out.push('-- tables can be reconciled afterwards.');
out.push('');
out.push('BEGIN;');
out.push('');

for (const a of animals) {
  const legacyId = a?.id;
  if (legacyId === undefined || legacyId === null) continue;

  // Deterministic so re-running maps the same animal to the same row.
  const hash = `legacy:${legacyId}`;
  counts.animals += 1;

  out.push(`-- ${a.name ?? 'unnamed'} (legacy id ${legacyId})`);
  out.push(
    `INSERT INTO animals (name, species, description, location, unique_hash, status, profile_image_url, last_seen_at, last_fed_at, notes)\n` +
      `VALUES (${q(a.name)}, ${q(a.animal_type)}, ${q(a.description)}, ${q(a.location)}, ${q(hash)}, ` +
      `${q(a.status ?? 'active')}, ${q(a.profile_image)}, ${ts(a.last_seen)}, ${ts(a.last_fed)}, ${q(`legacy_id=${legacyId}`)})\n` +
      `ON CONFLICT (unique_hash) DO UPDATE SET\n` +
      `  name = EXCLUDED.name, description = EXCLUDED.description, location = EXCLUDED.location,\n` +
      `  status = EXCLUDED.status, profile_image_url = EXCLUDED.profile_image_url,\n` +
      `  last_seen_at = EXCLUDED.last_seen_at, last_fed_at = EXCLUDED.last_fed_at;`
  );

  const ref = `(SELECT id FROM animals WHERE unique_hash = ${q(hash)})`;

  for (const c of a.comments ?? []) {
    if (!c?.text) continue;
    counts.comments += 1;
    out.push(
      `INSERT INTO animal_comments (animal_id, comment_text, created_at)\n` +
        `SELECT ${ref}, ${q(c.text)}, ${ts(c.timestamp) === 'NULL' ? 'now()' : ts(c.timestamp)}\n` +
        `WHERE NOT EXISTS (SELECT 1 FROM animal_comments WHERE animal_id = ${ref} AND comment_text = ${q(c.text)});`
    );
  }

  for (const m of a.memories ?? []) {
    const text = m?.text ?? m?.content;
    if (!text) continue;
    counts.memories += 1;
    out.push(
      `INSERT INTO emotional_memories (animal_id, memory_text, memory_type, created_at)\n` +
        `SELECT ${ref}, ${q(text)}, ${q(m.memory_type ?? 'happy')}, ${ts(m.timestamp) === 'NULL' ? 'now()' : ts(m.timestamp)}\n` +
        `WHERE NOT EXISTS (SELECT 1 FROM emotional_memories WHERE animal_id = ${ref} AND memory_text = ${q(text)});`
    );
  }

  for (const r of a.medical_records ?? []) {
    const title = r?.title ?? r?.type;
    if (!title) continue;
    counts.medical += 1;
    out.push(
      `INSERT INTO medical_records (animal_id, record_type, description, created_at)\n` +
        `SELECT ${ref}, ${q(title)}, ${q(r.description)}, ${ts(r.date) === 'NULL' ? 'now()' : ts(r.date)}\n` +
        `WHERE NOT EXISTS (SELECT 1 FROM medical_records WHERE animal_id = ${ref} AND record_type = ${q(title)} AND description IS NOT DISTINCT FROM ${q(r.description)});`
    );
  }

  // The blob keeps only the latest care timestamps, not a history, so exactly
  // one event per kind can be recovered.
  for (const [field, kind] of [['last_seen', 'seen'], ['last_fed', 'fed']]) {
    if (!a[field]) continue;
    counts.care += 1;
    out.push(
      `INSERT INTO care_events (animal_id, event_type, created_at)\n` +
        `SELECT ${ref}, ${q(kind)}, ${ts(a[field])}\n` +
        `WHERE NOT EXISTS (SELECT 1 FROM care_events WHERE animal_id = ${ref} AND event_type = ${q(kind)} AND created_at = ${ts(a[field])});`
    );
  }

  out.push('');
}

out.push('COMMIT;');
out.push('');
out.push(
  `-- Expected: ${counts.animals} animals, ${counts.comments} comments, ` +
    `${counts.memories} memories, ${counts.medical} medical records, ${counts.care} care events.`
);

writeFileSync(outputPath, out.join('\n'), 'utf8');

console.log(`Wrote ${outputPath}`);
console.table(counts);
console.log(
  '\nNOT APPLIED. Review the SQL, then run it against the database yourself.\n' +
    'Remember the tables require auth.uid() on write — see the header of this file.'
);
